import pytest

from main import binary_search as search


@pytest.mark.parametrize("array,hours,expected", [
    ([3,6,7,11], 8, 4),
    ([30,11,23,4,20], 5, 30),
    ([30,11,23,4,20], 6, 23),

    ([1], 1, 1),
    ([10], 1, 10),
    ([10], 10, 1),
    ([10], 5, 2),
    ([10], 100, 1),

    ([5,5,5], 3, 5),
    ([5,5,5], 15, 1),
    ([5,5,5], 6, 3),
    ([5,5,5], 5, 5),
    ([5,5,5], 4, 5),

    ([3,6,7,11], 4, 11),
    ([1,2,3,4,5], 5, 5),

    ([3,6,7,11], 100, 1),
    ([1,1,1,1], 1000, 1),
    ([10**9], 10**9, 1),

    ([1,2,3], 3, 3),
    ([100,200,300], 3, 300),

    ([1], 1, 1),
    ([10**9], 1, 10**9),

    ([10**9, 10**9], 2, 10**9),
    ([10**9, 10**9], 3, 10**9),
    ([10**9, 10**9], 4, 5 * 10**8),
    ([10**9, 10**9], 10**9, 1),

    ([1], 1, 1),
    ([10**9], 10**9, 1),
    ([10**9], 1, 10**9),

    ([1,1,1,1], 4, 1),
    ([1,1,1,1], 5, 1),
])
def test_search(array, hours, expected):

    assert search(array, hours) == expected
