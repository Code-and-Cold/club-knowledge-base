import pytest

from main import binary_search as search


@pytest.mark.parametrize("array,target,expected", [
    ([-1,0,3,5,9,12], 9, 4),
    ([-1,0,3,5,9,12], 2, -1),

    ([5], 5, 0),
    ([5], -5, -1),
    ([5], 6, -1),
    ([1], 1, 0),
    ([1], 0, -1),

    ([1,2], 1, 0),
    ([1,2], 2, 1),
    ([1,2], 3, -1),
    ([1,2], 0, -1),

    ([1,2,3,4,5], 1, 0),

    ([1,2,3,4,5], 5, 4),

    ([1,2,3,4,5], 3, 2),

    ([1,2,3,4,5], 0, -1),
    ([-5,-3,-1,0,1], -10, -1),

    ([1,2,3,4,5], 6, -1),
    ([-5,-3,-1,0,1], 10, -1),

    ([-10,-5,-3,-1,0], -5, 1),
    ([-10,-5,-3,-1,0], -10, 0),
    ([-10,-5,-3,-1,0], 0, 4),
    ([-10,-5,-3,-1,0], -7, -1),

    ([-5,-4,-3,-2,-1], -3, 2),
    ([-5,-4,-3,-2,-1], -1, 4),
    ([-5,-4,-3,-2,-1], -5, 0),
    ([-5,-4,-3,-2,-1], -6, -1),
    ([-5,-4,-3,-2,-1], 0, -1),

    ([-3,-1,0,2,4], 0, 2),
    ([-3,-1,1,2,4], 0, -1),

    ([-10**4, 0, 10**4], -10**4, 0),
    ([-10**4, 0, 10**4], 10**4, 2),
    ([-10**4, 0, 10**4], 0, 1),
    ([-10**4, 0, 10**4], -10**4 - 1, -1),
    ([-10**4, 0, 10**4], 10**4 + 1, -1),

    (list(range(0, 1000, 2)), 0, 0),
    (list(range(0, 1000, 2)), 500, 250),
    (list(range(0, 1000, 2)), 998, 499),
    (list(range(0, 1000, 2)), 501, -1),
    (list(range(0, 1000, 2)), -2, -1),
    (list(range(0, 1000, 2)), 1000, -1),

    ([1,2,4,8,16,32,64,128,256,512], 1, 0),
    ([1,2,4,8,16,32,64,128,256,512], 512, 9),
    ([1,2,4,8,16,32,64,128,256,512], 256, 8),
    ([1,2,4,8,16,32,64,128,256,512], 3, -1),
])
def test_search(array, target, expected):

    assert search(array, target) == expected
